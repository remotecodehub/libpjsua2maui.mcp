using libpjsua2maui.mcp.Knowledge;

namespace libpjsua2maui.mcp.tests.MCP;

public sealed class SourceInspectionTests
{
    [Fact]
    public void Inspect_GeneratedCSharpRecordsSwigPinvokeAndLifecycleFacts()
    {
        var package = new PackageIdentity("libpjsua2maui");
        var version = PackageVersion.Parse("2.17.0.5");
        var identity = new KnowledgeSetIdentity(package, version);
        var artifact = new PackageArtifact(package, version, "src/Platforms/Windows/pjsua2maui/pjsua2/Account.cs", ArtifactKind.ManagedSource, "net10.0-windows10.0.19041");
        var acquisition = new PackageAcquisitionResult("C:/fixture.nupkg", new KnowledgeManifest(identity, artifacts: [artifact], status: KnowledgeManifestStatus.Validated), new PackageDocumentationValidation(version, new Dictionary<string, string>(), [], []));
        var content = """
            // This file was automatically generated by SWIG (https://www.swig.org).
            // Version 4.5.1
            public class Account : System.IDisposable {
              private System.Runtime.InteropServices.HandleRef swigCPtr;
              protected bool swigCMemOwn;
              [System.Runtime.InteropServices.DllImport("pjsua2", EntryPoint="CSharp_libpjsua2fmaui_new_Account___")]
              public static extern System.IntPtr new_Account();
              public void Dispose() { pjsua2PINVOKE.delete_Account(swigCPtr); }
              public void SwigDirectorConnect() { }
            }
            """;

        var result = new SourceInspection().Inspect(acquisition, artifact, content);

        Assert.Contains("Account", result.Symbols);
        Assert.Contains(result.Relationships, item => item.RelationshipType == "managed-to-swig-source" && item.Confidence == KnowledgeConfidence.Confirmed);
        Assert.Contains(result.Relationships, item => item.RelationshipType == "swig-to-native-entrypoint");
        Assert.Contains(result.LifecycleFacts, item => item.Kind == LifecycleFactKind.Handle);
        Assert.Contains(result.LifecycleFacts, item => item.Kind == LifecycleFactKind.Ownership);
        Assert.Contains(result.LifecycleFacts, item => item.Kind == LifecycleFactKind.Disposal);
        Assert.Contains(result.LifecycleFacts, item => item.Kind == LifecycleFactKind.NativeDestruction);
        Assert.Contains(result.LifecycleFacts, item => item.Kind == LifecycleFactKind.CallbackRegistration);
    }

    [Fact]
    public void Inspect_NativeWrapperPreservesPartialPjprojectEvidence()
    {
        var package = new PackageIdentity("libpjsua2maui");
        var version = PackageVersion.Parse("2.17.0.5");
        var identity = new KnowledgeSetIdentity(package, version);
        var artifact = new PackageArtifact(package, version, "src/Platforms/Windows/cpp/pjsua2_wrap.cpp", ArtifactKind.NativeSource);
        var acquisition = new PackageAcquisitionResult("C:/fixture.nupkg", new KnowledgeManifest(identity, artifacts: [artifact], status: KnowledgeManifestStatus.Validated), new PackageDocumentationValidation(version, new Dictionary<string, string>(), [], []));

        var result = new SourceInspection().Inspect(acquisition, artifact, "#include <pjsua2/endpoint.hpp>\nvoid CSharp_libpjsua2fmaui_Endpoint_libCreate() {}\n");

        Assert.Contains("CSharp_libpjsua2fmaui_Endpoint_libCreate", result.Symbols);
        var relation = Assert.Single(result.Relationships, item => item.RelationshipType == "native-to-pjproject-text");
        Assert.Equal(KnowledgeFactStatus.Partial, relation.Status);
        Assert.Equal(KnowledgeConfidence.Strong, relation.Confidence);
    }

    [Fact]
    public void Inspect_ManagedSourceWithoutInteropEvidenceRemainsEmpty()
    {
        var (acquisition, artifact) = CreateFixture("src/Platforms/iOS/pjsua2maui/pjsua2/Plain.cs", ArtifactKind.ManagedSource);

        var result = new SourceInspection().Inspect(acquisition, artifact, "namespace Example; public class Plain { }");

        Assert.Single(result.Relationships);
        Assert.Empty(result.LifecycleFacts);
        Assert.Contains("Plain", result.Symbols);
    }

    [Fact]
    public void Inspect_NativeSourceWithoutPjprojectIncludeDoesNotInventMapping()
    {
        var (acquisition, artifact) = CreateFixture("src/Platforms/iOS/cpp/custom.cpp", ArtifactKind.NativeSource);

        var result = new SourceInspection().Inspect(acquisition, artifact, "#include <custom.h>\nvoid CSharp_libpjsua2fmaui_custom_function() {}\n");

        Assert.DoesNotContain(result.Relationships, item => item.RelationshipType == "native-to-pjproject-text");
        Assert.Contains("CSharp_libpjsua2fmaui_custom_function", result.Symbols);
    }

    [Fact]
    public void Inspect_HeaderWithoutSymbolsProducesNoNativeRelationship()
    {
        var (acquisition, artifact) = CreateFixture("src/Platforms/iOS/cpp/custom.hpp", ArtifactKind.NativeHeader);

        var result = new SourceInspection().Inspect(acquisition, artifact, "#include <vector>\n");

        Assert.Empty(result.Relationships);
        Assert.Empty(result.Symbols);
    }

    private static (PackageAcquisitionResult Acquisition, PackageArtifact Artifact) CreateFixture(string path, ArtifactKind kind)
    {
        var package = new PackageIdentity("libpjsua2maui");
        var version = PackageVersion.Parse("2.17.0.5");
        var identity = new KnowledgeSetIdentity(package, version);
        var artifact = new PackageArtifact(package, version, path, kind, "net10.0-ios26.0");
        var manifest = new KnowledgeManifest(identity, artifacts: [artifact], status: KnowledgeManifestStatus.Validated);
        var acquisition = new PackageAcquisitionResult("C:/fixture.nupkg", manifest, new PackageDocumentationValidation(version, new Dictionary<string, string>(), [], []));
        return (acquisition, artifact);
    }
}
