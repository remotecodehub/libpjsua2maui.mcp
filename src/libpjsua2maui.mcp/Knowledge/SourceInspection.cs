using System.Text.RegularExpressions;

namespace libpjsua2maui.mcp.Knowledge;

/// <summary>Inspects generated bindings and resolves source relationships without loading native code.</summary>
public sealed class SourceInspection
{
    private static readonly Regex SwigVersionPattern = new("automatically generated by SWIG.*?Version\\s+(?<version>[0-9.]+)", RegexOptions.IgnoreCase | RegexOptions.Singleline | RegexOptions.Compiled);
    private static readonly Regex CSharpTypePattern = new("\\b(?:public|internal|protected)?\\s*(?:partial\\s+)?(?:class|struct|record|enum|delegate)\\s+(?<name>[A-Za-z_][A-Za-z0-9_]*)", RegexOptions.Compiled);
    private static readonly Regex PInvokeCallPattern = new("pjsua2PINVOKE\\.(?<call>[A-Za-z_][A-Za-z0-9_]*)\\s*\\(", RegexOptions.Compiled);
    private static readonly Regex PInvokeDeclarationPattern = new("DllImport\\s*\\(\\s*\\\"(?<library>[^\\\"]+)\\\"(?<arguments>[^)]*)\\)[\\s\\S]{0,500}?(?:extern\\s+)?(?<method>[A-Za-z_][A-Za-z0-9_]*)\\s*\\(", RegexOptions.Compiled);
    private static readonly Regex PInvokeEntryPointPattern = new("EntryPoint\\s*=\\s*\\\"(?<entry>[^\\\"]+)\\\"", RegexOptions.Compiled);
    private static readonly Regex CppDefinitionPattern = new("CSharp_libpjsua2fmaui_(?<symbol>[A-Za-z_][A-Za-z0-9_]*?)(?<suffix>_{0,3})\\s*\\((?<parameters>[^)]*)\\)\\s*\\{", RegexOptions.Compiled);
    private static readonly Regex IncludePattern = new("^\\s*#include\\s*[<\\\"](?<include>[^>\\\"]+)[>\\\"]", RegexOptions.Multiline | RegexOptions.Compiled);
    private static readonly Regex PjInstanceCallPattern = new(@"\(?\s*(?<variable>[A-Za-z_][A-Za-z0-9_]*)\s*\)?->(?<method>[A-Za-z_][A-Za-z0-9_]*)\s*\(", RegexOptions.Compiled);
    private static readonly Regex PjQualifiedCallPattern = new(@"pj::(?<type>[A-Za-z_][A-Za-z0-9_]*)::(?<method>[A-Za-z_][A-Za-z0-9_]*)\s*\(", RegexOptions.Compiled);
    private static readonly Regex PjVariablePattern = new(@"\bpj::(?<type>[A-Za-z_][A-Za-z0-9_]*)\s*(?:\*|&)\s*(?<variable>[A-Za-z_][A-Za-z0-9_]*)", RegexOptions.Compiled);
    private static readonly Regex AnyNativeVariablePattern = new(@"\b(?:pj|std)::[^;\r\n]*[&*]\s*(?<variable>arg[0-9]+)\b", RegexOptions.Compiled);

    /// <summary>Returns facts supported by one published source artifact.</summary>
    public SourceInspectionResult Inspect(PackageAcquisitionResult acquisition, PackageArtifact artifact, string content)
    {
        ArgumentNullException.ThrowIfNull(acquisition);
        ArgumentNullException.ThrowIfNull(artifact);
        ArgumentNullException.ThrowIfNull(content);

        var provenance = PackageProvenance(acquisition, artifact, "Source text read directly from the acquired .nupkg.");
        var relationships = new List<KnowledgeRelationship>();
        var lifecycle = new List<LifecycleFact>();
        var symbols = new List<string>();
        var coverage = new SourceInspectionCoverage();
        var diagnostics = new List<SourceInspectionDiagnostic>();

        if (artifact.Kind == ArtifactKind.ManagedSource)
        {
            var swigVersion = SwigVersionPattern.Match(content).Groups["version"].Value;
            var typeMatches = CSharpTypePattern.Matches(content).ToArray();
            coverage = coverage with
            {
                ManagedTypesDiscovered = typeMatches.Length,
                ManagedMembersDiscovered = CountManagedMembers(content)
            };
            foreach (Match match in typeMatches)
            {
                var managedName = match.Groups["name"].Value;
                symbols.Add(managedName);
                var managed = Node(KnowledgeNodeKind.ManagedSymbol, $"source:{artifact.RelativePath}::{managedName}");
                var wrapper = Node(KnowledgeNodeKind.SwigSymbol, $"swig-source:{artifact.RelativePath}::{managedName}");
                relationships.Add(Relationship(acquisition, "managed-to-swig-source", managed, wrapper, swigVersion.Length == 0 ? KnowledgeFactStatus.Partial : KnowledgeFactStatus.Established, provenance, swigVersion.Length == 0 ? KnowledgeConfidence.Strong : KnowledgeConfidence.Confirmed));
            }

            foreach (var declaration in ParsePInvokes(artifact.RelativePath, content))
            {
                relationships.Add(Relationship(acquisition, "swig-to-native-entrypoint", Node(KnowledgeNodeKind.SwigSymbol, $"pinvoke:{declaration.Method}"), Node(KnowledgeNodeKind.WrapperSymbol, $"native-entry:{declaration.EntryPoint}"), KnowledgeFactStatus.Partial, provenance, KnowledgeConfidence.Strong));
            }

            AddLifecycleFacts(acquisition, artifact, content, provenance, lifecycle);
        }
        else if (artifact.Kind is ArtifactKind.NativeSource or ArtifactKind.NativeHeader)
        {
            foreach (Match match in CppDefinitionPattern.Matches(content))
            {
                var symbol = $"CSharp_libpjsua2fmaui_{match.Groups["symbol"].Value}{match.Groups["suffix"].Value}";
                symbols.Add(symbol);
                relationships.Add(Relationship(acquisition, "native-wrapper-symbol", Node(KnowledgeNodeKind.WrapperSymbol, $"wrapper:{artifact.RelativePath}::{symbol}"), Node(KnowledgeNodeKind.NativeSymbol, $"native:{symbol}"), KnowledgeFactStatus.Established, provenance, KnowledgeConfidence.Confirmed));
            }

            foreach (Match match in IncludePattern.Matches(content))
            {
                var include = match.Groups["include"].Value;
                if (include.Contains("pjsua2", StringComparison.OrdinalIgnoreCase) || include.Contains("pj/", StringComparison.OrdinalIgnoreCase))
                {
                    relationships.Add(Relationship(acquisition, "native-to-pjproject-text", Node(KnowledgeNodeKind.NativeSymbol, $"source:{artifact.RelativePath}"), Node(KnowledgeNodeKind.TextReference, $"include:{include}"), KnowledgeFactStatus.Partial, provenance, KnowledgeConfidence.Strong));
                }
            }
        }

        return new SourceInspectionResult(artifact, symbols.Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToArray(), relationships, lifecycle, provenance, coverage, diagnostics);
    }

    /// <summary>Correlates direct managed calls, P/Invoke declarations, wrapper bodies and pjproject sources.</summary>
    public IReadOnlyList<KnowledgeRelationship> InspectRepositoryMappings(PackageAcquisitionResult acquisition, IReadOnlyDictionary<string, string> packageSources, SourceRepositoryDescriptor repository)
        => InspectRepositoryMappingsDetailed(acquisition, packageSources, repository).Relationships;

    /// <summary>Correlates repository sources and returns relationships, coverage denominators and parser diagnostics.</summary>
    public RepositoryMappingInspectionResult InspectRepositoryMappingsDetailed(PackageAcquisitionResult acquisition, IReadOnlyDictionary<string, string> packageSources, SourceRepositoryDescriptor repository)
    {
        ArgumentNullException.ThrowIfNull(acquisition);
        ArgumentNullException.ThrowIfNull(packageSources);
        ArgumentNullException.ThrowIfNull(repository);

        var results = new List<KnowledgeRelationship>();
        var diagnostics = new List<SourceInspectionDiagnostic>();
        var managedSources = packageSources.Where(item => item.Key.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) && item.Key.Contains("/pjsua2/", StringComparison.OrdinalIgnoreCase)).OrderBy(item => item.Key, StringComparer.Ordinal);
        var pinvoke = packageSources.Where(item => item.Key.EndsWith("pjsua2PINVOKE.cs", StringComparison.OrdinalIgnoreCase)).SelectMany(item => ParsePInvokes(item.Key, item.Value)).OrderBy(item => item.Path, StringComparer.Ordinal).ThenBy(item => item.Method, StringComparer.Ordinal).ToArray();
        var wrappers = packageSources.Where(item => item.Key.EndsWith("pjsua2_wrap.cpp", StringComparison.OrdinalIgnoreCase)).SelectMany(item => ParseCppDefinitions(item.Key, item.Value)).ToDictionary(item => item.EntryPoint, StringComparer.Ordinal);
        var coverage = new SourceInspectionCoverage
        {
            ManagedTypesDiscovered = managedSources.Sum(item => CSharpTypePattern.Matches(item.Value).Count),
            ManagedMembersDiscovered = managedSources.Sum(item => CountManagedMembers(item.Value)),
            SwigCallsDiscovered = managedSources.Sum(item => PInvokeCallPattern.Matches(item.Value).Count),
            PInvokeDeclarationsDiscovered = pinvoke.Select(item => $"{item.Path}|{item.Method}|{item.EntryPoint}").Distinct(StringComparer.Ordinal).Count(),
            PInvokeDeclarationsResolvedToWrapper = pinvoke.Count(item => wrappers.ContainsKey(item.EntryPoint)),
            WrapperDefinitionsDiscovered = wrappers.Count
        };
        var membersWithCalls = new HashSet<string>(StringComparer.Ordinal);
        var resolvedSwigCalls = 0;

        foreach (var managed in managedSources)
        {
            var typeName = Path.GetFileNameWithoutExtension(managed.Key);
            foreach (Match call in PInvokeCallPattern.Matches(managed.Value))
            {
                var method = FindManagedMember(managed.Value, call.Index, typeName);
                var callName = call.Groups["call"].Value;
                membersWithCalls.Add($"{managed.Key}::{method}");
                var managedNode = Node(KnowledgeNodeKind.ManagedSymbol, $"managed:{managed.Key}::{method}");
                var swigNode = Node(KnowledgeNodeKind.SwigSymbol, $"swig:{managed.Key}::{callName}");
                var memberDelimited = !method.Equals(typeName, StringComparison.Ordinal) || HasConstructorBefore(managed.Value, call.Index, typeName);
                if (!memberDelimited)
                {
                    diagnostics.Add(new SourceInspectionDiagnostic(managed.Key, "managed member containing P/Invoke call", $"The direct pjsua2PINVOKE.{callName} call was found, but the enclosing managed member could not be delimited by the current source parser.", SourceInspectionDiagnosticKind.Unparsed));
                }

                results.Add(Relationship(acquisition, "managed-member-to-swig-call", managedNode, swigNode, memberDelimited ? KnowledgeFactStatus.Established : KnowledgeFactStatus.Partial, PackageSourceProvenance(acquisition, managed.Key, memberDelimited ? $"Direct generated C# call pjsua2PINVOKE.{callName}." : $"Direct generated C# call pjsua2PINVOKE.{callName}; enclosing member is not delimited."), memberDelimited ? KnowledgeConfidence.Confirmed : KnowledgeConfidence.Strong));

                var declarationCandidates = pinvoke.Where(item => item.Method.Equals(callName, StringComparison.Ordinal) && SamePlatform(managed.Key, item.Path)).ToArray();
                if (declarationCandidates.Length == 0)
                {
                    coverage = coverage with { SwigCallsWithoutPInvoke = coverage.SwigCallsWithoutPInvoke + 1 };
                    results.Add(Relationship(acquisition, "swig-call-to-pinvoke", swigNode, Unknown(KnowledgeNodeKind.WrapperSymbol), KnowledgeFactStatus.Unknown, PackageSourceProvenance(acquisition, managed.Key, $"No exact P/Invoke declaration was found for pjsua2PINVOKE.{callName}."), KnowledgeConfidence.Strong));
                    continue;
                }

                if (declarationCandidates.Select(item => item.EntryPoint).Distinct(StringComparer.Ordinal).Count() != 1)
                {
                    results.Add(Relationship(acquisition, "swig-call-to-pinvoke", swigNode, Unknown(KnowledgeNodeKind.WrapperSymbol), KnowledgeFactStatus.Conflicting, PackageSourceProvenance(acquisition, managed.Key, $"More than one exact-platform P/Invoke entry point was found for pjsua2PINVOKE.{callName}."), KnowledgeConfidence.Strong));
                    continue;
                }

                var declaration = declarationCandidates[0];

                resolvedSwigCalls++;

                var pinvokeNode = Node(KnowledgeNodeKind.SwigSymbol, $"pinvoke:{declaration.Path}::{declaration.Method}::{declaration.EntryPoint}");
                results.Add(Relationship(acquisition, "swig-call-to-pinvoke", swigNode, pinvokeNode, KnowledgeFactStatus.Established, PackageSourceProvenance(acquisition, declaration.Path, $"DllImport library '{declaration.Library}' EntryPoint '{declaration.EntryPoint}' declares pjsua2PINVOKE.{declaration.Method}."), KnowledgeConfidence.Confirmed));

                if (!wrappers.TryGetValue(declaration.EntryPoint, out var wrapper))
                {
                    results.Add(Relationship(acquisition, "pinvoke-to-native-wrapper", pinvokeNode, Unknown(KnowledgeNodeKind.WrapperSymbol), KnowledgeFactStatus.Unknown, PackageSourceProvenance(acquisition, declaration.Path, $"No generated wrapper definition was found for EntryPoint '{declaration.EntryPoint}'."), KnowledgeConfidence.Strong));
                    continue;
                }

                var wrapperNode = Node(KnowledgeNodeKind.WrapperSymbol, $"wrapper:{wrapper.Path}::{wrapper.EntryPoint}");
                results.Add(Relationship(acquisition, "pinvoke-to-native-wrapper", pinvokeNode, wrapperNode, KnowledgeFactStatus.Established, RepositoryProvenance(acquisition, repository, wrapper.Path, managed.Key, "The exact P/Invoke entry point has a matching generated C++ definition."), KnowledgeConfidence.Confirmed));
                AddPjprojectMappings(acquisition, repository, wrapper, wrapperNode, results, diagnostics, ref coverage);
            }
        }

        var applicableManagedMembers = managedSources.Sum(item => CountApplicableManagedMembers(item.Value));
        return new RepositoryMappingInspectionResult(results, coverage with
        {
            ManagedMembersApplicableToSwig = applicableManagedMembers,
            ManagedMembersWithSwigCalls = membersWithCalls.Count,
            ManagedMembersWithoutDirectSwigCall = Math.Max(0, applicableManagedMembers - membersWithCalls.Count),
            SwigCallsResolvedToPInvoke = resolvedSwigCalls
        }, diagnostics);
    }

    private static void AddPjprojectMappings(PackageAcquisitionResult acquisition, SourceRepositoryDescriptor repository, CppDefinition wrapper, KnowledgeNodeReference wrapperNode, ICollection<KnowledgeRelationship> relationships, ICollection<SourceInspectionDiagnostic> diagnostics, ref SourceInspectionCoverage coverage)
    {
        var variables = PjVariablePattern.Matches(wrapper.Body)
            .ToDictionary(match => match.Groups["variable"].Value, match => match.Groups["type"].Value, StringComparer.Ordinal);
        var qualifiedPairs = PjQualifiedCallPattern.Matches(wrapper.Body)
            .Select(match => (Type: match.Groups["type"].Value, Method: match.Groups["method"].Value));
        var instancePairs = PjInstanceCallPattern.Matches(wrapper.Body)
            .Where(match => variables.ContainsKey(match.Groups["variable"].Value))
            .Select(match => (Type: variables[match.Groups["variable"].Value], Method: match.Groups["method"].Value));
        var lifecyclePairs = ConstructorOrDestructorPair(wrapper, variables);
        var pairs = qualifiedPairs.Concat(instancePairs).Concat(lifecyclePairs).Distinct().ToArray();
        coverage = coverage with { WrapperInvocationsDiscovered = coverage.WrapperInvocationsDiscovered + PjQualifiedCallPattern.Matches(wrapper.Body).Count + PjInstanceCallPattern.Matches(wrapper.Body).Count + lifecyclePairs.Length };
        var unsupportedReceiver = PjInstanceCallPattern.Matches(wrapper.Body)
            .FirstOrDefault(match => match.Groups["variable"].Value.StartsWith("arg", StringComparison.Ordinal) && !AnyNativeVariablePattern.Matches(wrapper.Body).Cast<Match>().Any(declaration => declaration.Groups["variable"].Value.Equals(match.Groups["variable"].Value, StringComparison.Ordinal)));
        if (unsupportedReceiver is not null && wrapper.Body.Contains("pj::", StringComparison.Ordinal))
        {
            diagnostics.Add(new SourceInspectionDiagnostic(wrapper.Path, "pjproject instance invocation", "The wrapper contains an instance call, but no pj:: pointer/reference declaration matched its receiver.", SourceInspectionDiagnosticKind.Unparsed));
        }
        if (pairs.Length == 0)
        {
            relationships.Add(Relationship(acquisition, "native-wrapper-to-pjproject", wrapperNode, Unknown(KnowledgeNodeKind.NativeSymbol), KnowledgeFactStatus.Unknown, RepositoryProvenance(acquisition, repository, wrapper.Path, null, "The wrapper definition contains no resolvable pj:: type/member invocation."), KnowledgeConfidence.Strong));
            return;
        }

        var resolved = false;
        foreach (var pair in pairs)
        {
            var type = pair.Type!;
            var method = pair.Method;
                var header = FindPjHeader(repository.PjprojectRootPath, type);
                var declaration = header is not null && ContainsDeclaration(header.Value.Content, type, method);
                var implementation = FindPjImplementation(repository.PjprojectRootPath, type, method);
                if (!declaration && implementation is null) continue;

                coverage = coverage with
                {
                    WrapperInvocationsResolvedToPjprojectDeclaration = coverage.WrapperInvocationsResolvedToPjprojectDeclaration + (declaration ? 1 : 0),
                    PjprojectDeclarationsResolvedToImplementation = coverage.PjprojectDeclarationsResolvedToImplementation + (implementation is not null ? 1 : 0)
                };

                resolved = true;
                var declarationPath = header?.RelativePath ?? implementation!.Value.RelativePath;
                var declarationNode = Node(KnowledgeNodeKind.NativeSymbol, $"pj-declaration:{declarationPath}::{type}.{method}");
                var status = declaration && implementation is not null ? KnowledgeFactStatus.Established : KnowledgeFactStatus.Partial;
                relationships.Add(Relationship(acquisition, "native-wrapper-to-pjproject-declaration", wrapperNode, declarationNode, status, RepositoryProvenance(acquisition, repository, declarationPath, wrapper.Path, $"Generated wrapper calls pj::{type}::{method}; declaration evidence was resolved."), declaration ? KnowledgeConfidence.Confirmed : KnowledgeConfidence.Strong));
                if (implementation is not null)
                {
                    var implementationNode = Node(KnowledgeNodeKind.NativeSymbol, $"pj-implementation:{implementation.Value.RelativePath}::{type}::{method}");
                    relationships.Add(Relationship(acquisition, "pjproject-declaration-to-implementation", declarationNode, implementationNode, KnowledgeFactStatus.Established, RepositoryProvenance(acquisition, repository, implementation.Value.RelativePath, wrapper.Path, "Matching pjproject implementation definition was found."), KnowledgeConfidence.Confirmed));
                }
        }

        if (!resolved) relationships.Add(Relationship(acquisition, "native-wrapper-to-pjproject", wrapperNode, Unknown(KnowledgeNodeKind.NativeSymbol), KnowledgeFactStatus.Unknown, RepositoryProvenance(acquisition, repository, wrapper.Path, null, "No matching pjproject declaration or implementation was found."), KnowledgeConfidence.Strong));
    }

    private static void AddLifecycleFacts(PackageAcquisitionResult acquisition, PackageArtifact artifact, string content, FactProvenance provenance, ICollection<LifecycleFact> lifecycle)
    {
        foreach (var type in FindManagedTypes(content))
        {
            var subject = Node(KnowledgeNodeKind.ManagedSymbol, $"managed:{artifact.RelativePath}::{type.Name}");
            var body = type.Body;
            if (body.Contains("HandleRef", StringComparison.Ordinal)) lifecycle.Add(CreateLifecycle(acquisition, subject, LifecycleFactKind.Handle, "HandleRef field/use belongs to this generated type.", provenance));
            if (body.Contains("swigCMemOwn", StringComparison.Ordinal)) lifecycle.Add(CreateLifecycle(acquisition, subject, LifecycleFactKind.Ownership, "swigCMemOwn field controls native destruction ownership for this generated type.", provenance));
            if (Regex.IsMatch(body, @"\bDispose\s*\(", RegexOptions.CultureInvariant)) lifecycle.Add(CreateLifecycle(acquisition, subject, LifecycleFactKind.Disposal, "Dispose() belongs to this generated type.", provenance));
            if (body.Contains($"~{type.Name}(", StringComparison.Ordinal) || body.Contains("delete_", StringComparison.Ordinal)) lifecycle.Add(CreateLifecycle(acquisition, subject, LifecycleFactKind.NativeDestruction, "A finalizer or delete_* path is present in this generated type.", provenance));
            if (body.Contains("director", StringComparison.OrdinalIgnoreCase) || body.Contains("SwigDelegate", StringComparison.Ordinal)) lifecycle.Add(CreateLifecycle(acquisition, subject, LifecycleFactKind.CallbackRegistration, "Director/delegate callback infrastructure belongs to this generated type.", provenance));
        }
    }

    private static (string Type, string Method)[] ConstructorOrDestructorPair(CppDefinition wrapper, IReadOnlyDictionary<string, string> variables)
    {
        var constructor = Regex.Match(wrapper.EntryPoint, @"new_(?<type>[A-Za-z_][A-Za-z0-9_]*?)(?:_{1,3})?$", RegexOptions.CultureInvariant);
        if (constructor.Success && variables.Values.Contains(constructor.Groups["type"].Value, StringComparer.Ordinal))
        {
            return [(constructor.Groups["type"].Value, "#ctor")];
        }

        var destructor = Regex.Match(wrapper.EntryPoint, @"delete_(?<type>[A-Za-z_][A-Za-z0-9_]*?)(?:_{1,3})?$", RegexOptions.CultureInvariant);
        return destructor.Success && variables.Values.Contains(destructor.Groups["type"].Value, StringComparer.Ordinal)
            ? [(destructor.Groups["type"].Value, "#dtor")]
            : [];
    }

    private static LifecycleFact CreateLifecycle(PackageAcquisitionResult acquisition, KnowledgeNodeReference subject, LifecycleFactKind kind, string value, FactProvenance provenance) => new(acquisition.Manifest.Identity, subject, kind, KnowledgeFactStatus.Established, value, provenance, KnowledgeConfidence.Confirmed);
    private static FactProvenance PackageProvenance(PackageAcquisitionResult acquisition, PackageArtifact artifact, string evidence) => new(acquisition.Manifest.Identity, ProvenanceKind.PackageArtifact, artifact.RelativePath, sourceReference: artifact.RelativePath, targetFramework: artifact.TargetFramework, runtimeIdentifier: artifact.RuntimeIdentifier, evidence: evidence);
    private static FactProvenance PackageSourceProvenance(PackageAcquisitionResult acquisition, string path, string evidence)
    {
        var artifact = acquisition.Manifest.Artifacts.FirstOrDefault(item => item.RelativePath.Equals(path, StringComparison.Ordinal));
        return new FactProvenance(acquisition.Manifest.Identity, ProvenanceKind.PackageArtifact, path, sourceReference: path, targetFramework: artifact?.TargetFramework, runtimeIdentifier: artifact?.RuntimeIdentifier, evidence: evidence);
    }

    private static FactProvenance RepositoryProvenance(PackageAcquisitionResult acquisition, SourceRepositoryDescriptor repository, string relativePath, string? packagePath, string evidence)
    {
        var artifact = packagePath is null ? null : acquisition.Manifest.Artifacts.FirstOrDefault(item => item.RelativePath.Equals(packagePath, StringComparison.Ordinal));
        return new FactProvenance(acquisition.Manifest.Identity, ProvenanceKind.RepositorySource, sourceReference: relativePath, limitations: "Static source inspection does not validate runtime loading.", repository: repository.Repository, revision: repository.Revision, tag: repository.Tag, targetFramework: artifact?.TargetFramework, runtimeIdentifier: artifact?.RuntimeIdentifier, evidence: $"{evidence} Package source: {packagePath ?? "not available"}. pjproject revision: {repository.PjprojectRevision}. pjproject repository: {repository.PjprojectRepository}.");
    }
    private static KnowledgeNodeReference Node(KnowledgeNodeKind kind, string identifier) => new(kind, identifier);
    private static KnowledgeNodeReference Unknown(KnowledgeNodeKind kind) => new(kind, KnowledgeNodeResolution.Unknown, null);
    private static KnowledgeRelationship Relationship(PackageAcquisitionResult acquisition, string type, KnowledgeNodeReference source, KnowledgeNodeReference target, KnowledgeFactStatus status, FactProvenance provenance, KnowledgeConfidence confidence) => new(acquisition.Manifest.Identity, type, source, target, status, provenance, confidence);

    private static string FindManagedMember(string content, int position, string typeName)
    {
        var prefix = content[..position];
        var matches = Regex.Matches(prefix, "(?:public|protected|private|internal|static|virtual|override|sealed|async|\\s)+[A-Za-z_][A-Za-z0-9_<>,.?\\[\\]]*\\s+(?<name>[A-Za-z_][A-Za-z0-9_]*)\\s*\\(");
        var constructorMatches = Regex.Matches(prefix, $"(?:public|protected|private|internal)\\s+{Regex.Escape(typeName)}\\s*\\(");
        var candidates = matches.Cast<Match>().Concat(constructorMatches.Cast<Match>()).OrderBy(match => match.Index).ToArray();
        return candidates.Length == 0 ? typeName : candidates[^1].Groups["name"].Success ? candidates[^1].Groups["name"].Value : typeName;
    }

    private static int CountManagedMembers(string content)
    {
        return Regex.Matches(content, @"\b(?:public|protected|private|internal)\s+(?:static\s+|virtual\s+|override\s+|sealed\s+|async\s+)*[A-Za-z_][A-Za-z0-9_<>,.?\[\]]*\s+[A-Za-z_][A-Za-z0-9_]*\s*(?:\(|\{)", RegexOptions.CultureInvariant).Count;
    }

    private static IReadOnlyList<ManagedTypeRegion> FindManagedTypes(string content)
    {
        var regions = new List<ManagedTypeRegion>();
        foreach (Match match in CSharpTypePattern.Matches(content))
        {
            var open = content.IndexOf('{', match.Index + match.Length);
            if (open < 0)
            {
                regions.Add(new ManagedTypeRegion(match.Groups["name"].Value, string.Empty));
                continue;
            }

            var close = FindMatchingBrace(content, open);
            var body = close < 0 ? content[(open + 1)..] : content.Substring(open + 1, close - open - 1);
            regions.Add(new ManagedTypeRegion(match.Groups["name"].Value, body));
        }

        return regions;
    }

    private static IReadOnlyList<PInvokeDeclaration> ParsePInvokes(string path, string content)
    {
        var declarations = new List<PInvokeDeclaration>();
        foreach (Match match in PInvokeDeclarationPattern.Matches(content))
        {
            var entry = PInvokeEntryPointPattern.Match(match.Groups["arguments"].Value);
            if (entry.Success)
            {
                declarations.Add(new PInvokeDeclaration(path, match.Groups["library"].Value, match.Groups["method"].Value, entry.Groups["entry"].Value));
            }
        }

        return declarations;
    }

    private static IReadOnlyList<CppDefinition> ParseCppDefinitions(string path, string content)
    {
        var definitions = new List<CppDefinition>();
        foreach (Match match in CppDefinitionPattern.Matches(content))
        {
            var open = match.Index + match.Length - 1;
            var close = FindMatchingBrace(content, open);
            var body = close < 0 ? content[open..] : content.Substring(open + 1, close - open - 1);
            var symbol = match.Groups["symbol"].Value;
            var suffix = match.Groups["suffix"].Value;
            definitions.Add(new CppDefinition(path, $"CSharp_libpjsua2fmaui_{symbol}{suffix}", body));
        }

        return definitions;
    }

    private static int FindMatchingBrace(string content, int open)
    {
        var depth = 0;
        for (var index = open; index < content.Length; index++)
        {
            if (content[index] == '{') depth++;
            if (content[index] == '}' && --depth == 0) return index;
        }

        return -1;
    }

    private static (string RelativePath, string Content)? FindPjHeader(string root, string type)
    {
        var expected = Path.Combine(root, "pjsip", "include", "pjsua2", $"{type.ToLowerInvariant()}.hpp");
        if (File.Exists(expected)) return (Relative(root, expected), File.ReadAllText(expected));
        var match = Directory.EnumerateFiles(root, "*.hpp", SearchOption.AllDirectories).Order(StringComparer.OrdinalIgnoreCase).FirstOrDefault(path => Path.GetFileNameWithoutExtension(path).Equals(type, StringComparison.OrdinalIgnoreCase));
        return match is null ? null : (Relative(root, match), File.ReadAllText(match));
    }

    private static (string RelativePath, string Content)? FindPjImplementation(string root, string type, string method)
    {
        var expected = Path.Combine(root, "pjsip", "src", "pjsua2", $"{type.ToLowerInvariant()}.cpp");
        var candidates = File.Exists(expected) ? [expected] : Directory.EnumerateFiles(root, "*.cpp", SearchOption.AllDirectories).Order(StringComparer.OrdinalIgnoreCase).ToArray();
        foreach (var path in candidates)
        {
            var content = File.ReadAllText(path);
            var memberPattern = method switch
            {
                "#ctor" => $"\\b{Regex.Escape(type)}::{Regex.Escape(type)}\\s*\\(",
                "#dtor" => $"~{Regex.Escape(type)}\\s*\\(",
                _ => $"\\b{Regex.Escape(type)}::{Regex.Escape(method)}\\s*\\("
            };
            if (Regex.IsMatch(content, memberPattern, RegexOptions.CultureInvariant)) return (Relative(root, path), content);
        }

        return null;
    }

    private static bool ContainsDeclaration(string content, string type, string method)
    {
        if (!Regex.IsMatch(content, $"\\b(?:class|struct)\\s+{Regex.Escape(type)}\\b", RegexOptions.CultureInvariant)) return false;
        return method switch
        {
            "#ctor" => true,
            "#dtor" => Regex.IsMatch(content, $"~{Regex.Escape(type)}\\s*\\(", RegexOptions.CultureInvariant),
            _ => Regex.IsMatch(content, $"\\b{Regex.Escape(method)}\\s*\\(", RegexOptions.CultureInvariant)
        };
    }
    private static string Relative(string root, string path) => Path.GetRelativePath(root, path).Replace('\\', '/');

    private static int CountApplicableManagedMembers(string content)
    {
        return CountManagedMembers(content);
    }

    private static bool HasConstructorBefore(string content, int position, string typeName)
    {
        return Regex.IsMatch(content[..position], $"(?:public|protected|private|internal)\\s+{Regex.Escape(typeName)}\\s*\\(", RegexOptions.CultureInvariant);
    }

    private static bool SamePlatform(string managedPath, string pinvokePath)
    {
        return PlatformSegment(managedPath).Equals(PlatformSegment(pinvokePath), StringComparison.OrdinalIgnoreCase);
    }

    private static string PlatformSegment(string path)
    {
        var parts = path.Replace('\\', '/').Split('/', StringSplitOptions.RemoveEmptyEntries);
        var index = Array.FindIndex(parts, item => item.Equals("Platforms", StringComparison.OrdinalIgnoreCase));
        return index >= 0 && index + 1 < parts.Length ? parts[index + 1] : string.Empty;
    }

    private sealed record PInvokeDeclaration(string Path, string Library, string Method, string EntryPoint);
    private sealed record CppDefinition(string Path, string EntryPoint, string Body);
    private sealed record ManagedTypeRegion(string Name, string Body);
}
