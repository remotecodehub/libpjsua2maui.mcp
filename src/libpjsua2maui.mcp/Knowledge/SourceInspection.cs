using System.Text.RegularExpressions;

namespace libpjsua2maui.mcp.Knowledge;

/// <summary>Inspects source artifacts shipped by a package without compiling or loading native code.</summary>
public sealed class SourceInspection
{
    private static readonly Regex SwigVersionPattern = new("automatically generated by SWIG.*?Version\\s+(?<version>[0-9.]+)", RegexOptions.IgnoreCase | RegexOptions.Singleline | RegexOptions.Compiled);
    private static readonly Regex CSharpTypePattern = new("\\b(?:public|internal|protected)?\\s*(?:partial\\s+)?(?:class|struct|record|enum|delegate)\\s+(?<name>[A-Za-z_][A-Za-z0-9_]*)", RegexOptions.Compiled);
    private static readonly Regex CSharpPinvokePattern = new("(?:EntryPoint\\s*=\\s*\\\"(?<entry>[^\\\"]+)\\\"|pjsua2PINVOKE\\.(?<call>[A-Za-z_][A-Za-z0-9_]*))", RegexOptions.Compiled);
    private static readonly Regex CppSymbolPattern = new("\\b(?:CSharp_libpjsua2fmaui_|delete_|new_)(?<symbol>[A-Za-z_][A-Za-z0-9_]*)", RegexOptions.Compiled);
    private static readonly Regex IncludePattern = new("^\\s*#include\\s*[<\\\"](?<include>[^>\\\"]+)[>\\\"]", RegexOptions.Multiline | RegexOptions.Compiled);

    /// <summary>Returns relationships and lifecycle facts supported by one source file.</summary>
    public SourceInspectionResult Inspect(PackageAcquisitionResult acquisition, PackageArtifact artifact, string content)
    {
        ArgumentNullException.ThrowIfNull(acquisition);
        ArgumentNullException.ThrowIfNull(artifact);
        ArgumentNullException.ThrowIfNull(content);

        var sourceReference = artifact.RelativePath;
        var provenance = new FactProvenance(
            acquisition.Manifest.Identity,
            ProvenanceKind.PackageArtifact,
            artifact.RelativePath,
            sourceReference: sourceReference,
            targetFramework: artifact.TargetFramework,
            runtimeIdentifier: artifact.RuntimeIdentifier,
            evidence: "Source text read directly from the acquired .nupkg.");
        var relationships = new List<KnowledgeRelationship>();
        var lifecycle = new List<LifecycleFact>();
        var symbols = new List<string>();

        if (artifact.Kind == ArtifactKind.ManagedSource)
        {
            var swigVersion = SwigVersionPattern.Match(content).Groups["version"].Value;
            foreach (Match match in CSharpTypePattern.Matches(content))
            {
                var managedName = match.Groups["name"].Value;
                symbols.Add(managedName);
                var managed = new KnowledgeNodeReference(KnowledgeNodeKind.ManagedSymbol, $"source:{artifact.RelativePath}::{managedName}");
                var wrapper = new KnowledgeNodeReference(KnowledgeNodeKind.SwigSymbol, $"swig:{managedName}");
                relationships.Add(new KnowledgeRelationship(acquisition.Manifest.Identity, "managed-to-swig-source", managed, wrapper, KnowledgeFactStatus.Established, provenance, swigVersion.Length == 0 ? KnowledgeConfidence.Strong : KnowledgeConfidence.Confirmed));
            }

            foreach (Match match in CSharpPinvokePattern.Matches(content))
            {
                var entry = match.Groups["entry"].Success ? match.Groups["entry"].Value : match.Groups["call"].Value;
                var source = new KnowledgeNodeReference(KnowledgeNodeKind.SwigSymbol, $"pinvoke:{entry}");
                var target = new KnowledgeNodeReference(KnowledgeNodeKind.WrapperSymbol, $"native-entry:{entry}");
                relationships.Add(new KnowledgeRelationship(acquisition.Manifest.Identity, "swig-to-native-entrypoint", source, target, KnowledgeFactStatus.Partial, provenance, KnowledgeConfidence.Strong));
            }

            if (content.Contains("HandleRef", StringComparison.Ordinal))
                lifecycle.Add(CreateLifecycle(acquisition, artifact, LifecycleFactKind.Handle, "HandleRef is used by the generated managed wrapper.", provenance, KnowledgeFactStatus.Established));
            if (content.Contains("swigCMemOwn", StringComparison.Ordinal))
                lifecycle.Add(CreateLifecycle(acquisition, artifact, LifecycleFactKind.Ownership, "swigCMemOwn controls native destruction ownership.", provenance, KnowledgeFactStatus.Established));
            if (content.Contains("Dispose", StringComparison.Ordinal))
                lifecycle.Add(CreateLifecycle(acquisition, artifact, LifecycleFactKind.Disposal, "The generated wrapper exposes Dispose and/or a disposal path.", provenance, KnowledgeFactStatus.Established));
            if (content.Contains("delete_", StringComparison.Ordinal))
                lifecycle.Add(CreateLifecycle(acquisition, artifact, LifecycleFactKind.NativeDestruction, "The generated wrapper invokes a delete_* P/Invoke entry point.", provenance, KnowledgeFactStatus.Established));
            if (content.Contains("director", StringComparison.OrdinalIgnoreCase) || content.Contains("SwigDelegate", StringComparison.Ordinal))
                lifecycle.Add(CreateLifecycle(acquisition, artifact, LifecycleFactKind.CallbackRegistration, "SWIG director/delegate callback infrastructure is present.", provenance, KnowledgeFactStatus.Established));
        }
        else if (artifact.Kind is ArtifactKind.NativeSource or ArtifactKind.NativeHeader)
        {
            foreach (Match match in CppSymbolPattern.Matches(content))
            {
                var symbol = match.Value;
                symbols.Add(symbol);
                relationships.Add(new KnowledgeRelationship(acquisition.Manifest.Identity, "native-wrapper-symbol", new KnowledgeNodeReference(KnowledgeNodeKind.WrapperSymbol, $"source:{artifact.RelativePath}::{symbol}"), new KnowledgeNodeReference(KnowledgeNodeKind.NativeSymbol, $"native:{symbol}"), KnowledgeFactStatus.Established, provenance, KnowledgeConfidence.Strong));
            }

            foreach (Match match in IncludePattern.Matches(content))
            {
                var include = match.Groups["include"].Value;
                if (include.Contains("pjsua2", StringComparison.OrdinalIgnoreCase) || include.Contains("pj/", StringComparison.OrdinalIgnoreCase))
                {
                    relationships.Add(new KnowledgeRelationship(acquisition.Manifest.Identity, "native-to-pjproject-text", new KnowledgeNodeReference(KnowledgeNodeKind.NativeSymbol, $"source:{artifact.RelativePath}"), new KnowledgeNodeReference(KnowledgeNodeKind.TextReference, $"include:{include}"), KnowledgeFactStatus.Partial, provenance, KnowledgeConfidence.Strong));
                }
            }
        }

        return new SourceInspectionResult(artifact, symbols.Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToArray(), relationships, lifecycle, provenance);
    }

    private static LifecycleFact CreateLifecycle(PackageAcquisitionResult acquisition, PackageArtifact artifact, LifecycleFactKind kind, string value, FactProvenance provenance, KnowledgeFactStatus status)
    {
        return new LifecycleFact(acquisition.Manifest.Identity, new KnowledgeNodeReference(KnowledgeNodeKind.ManagedSymbol, $"source:{artifact.RelativePath}"), kind, status, value, provenance, KnowledgeConfidence.Confirmed);
    }
}
